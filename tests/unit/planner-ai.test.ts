import { afterEach, describe, expect, it } from "vitest";
import { disabledAiService, getPlannerAi, setPlannerAi, type ResearchPlanAiService } from "@/lib/ai/planner-ai";
import { generateMaterial } from "@/lib/research-planner/materials";
import { SECTION_SCHEMAS } from "@/lib/research-planner/schemas";
import { materialContext } from "./fixtures/plan";

afterEach(() => setPlannerAi(disabledAiService));

describe("AI readiness", () => {
  it("is disabled by default and refuses to generate", async () => {
    const ai = getPlannerAi();
    expect(ai.enabled).toBe(false);
    const result = await ai.generateSection({ section: "interview_guide", context: materialContext });
    expect(result).toMatchObject({ ok: false, reason: "disabled" });
  });

  it("does not affect the deterministic workflow", () => {
    expect(() => generateMaterial("interview_guide", materialContext)).not.toThrow();
  });

  it("lets a future provider fill the same section schemas", async () => {
    const provider: ResearchPlanAiService = {
      enabled: true,
      async generateSection() {
        return { ok: true, content: { questions: ["Generated by a provider"] } };
      },
    };
    setPlannerAi(provider);
    const result = await getPlannerAi().generateSection({ section: "pre_test_questions", context: materialContext });
    expect(result.ok).toBe(true);
    if (result.ok) expect(SECTION_SCHEMAS.pre_test_questions.safeParse(result.content).success).toBe(true);
  });
});
